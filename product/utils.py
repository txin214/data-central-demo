def markdown_to_pdf(markdown_content, filename="quote_report.pdf"):
    """
    Convert markdown content directly to PDF using ReportLab.
    """
    pdf_buffer = BytesIO()
    doc = SimpleDocTemplate(pdf_buffer, pagesize=A4, 
                          leftMargin=40, rightMargin=40, 
                          topMargin=40, bottomMargin=40)
    
    styles = getSampleStyleSheet()
    
    # Custom styles for better formatting
    title_style = ParagraphStyle(
        'CustomTitle',
        parent=styles['Heading1'],
        fontSize=18,
        spaceAfter=30,
        textColor=colors.black,
        alignment=TA_LEFT,
        fontName='Helvetica-Bold'
    )
    
    heading_style = ParagraphStyle(
        'CustomHeading',
        parent=styles['Heading2'],
        fontSize=14,
        spaceAfter=20,
        textColor=colors.black,
        alignment=TA_LEFT,
        fontName='Helvetica-Bold'
    )
    
    normal_style = ParagraphStyle(
        'CustomNormal',
        parent=styles['Normal'],
        fontSize=10,
        spaceAfter=6,
        textColor=colors.black,
        alignment=TA_LEFT
    )
    
    bold_style = ParagraphStyle(
        'CustomBold',
        parent=styles['Normal'],
        fontSize=10,
        spaceAfter=6,
        textColor=colors.black,
        alignment=TA_LEFT,
        fontName='Helvetica-Bold'
    )
    
    # Parse markdown content and create PDF elements
    story = []
    lines = markdown_content.split('\n')
    in_table = False
    table_data = []
    
    # Add the header first
    logo_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'static', 'crm', 'nologo.png')
    header_data = []
    
    if os.path.exists(logo_path):
        try:
            logo = Image(logo_path, width=150, height=45, kind='proportional')
            header_left = logo
        except Exception as e:
            print(f"Error loading logo: {e}")
            header_left = Paragraph("Allen Kitchen & Bath", title_style)
    else:
        header_left = Paragraph("Allen Kitchen & Bath", title_style)
    
    # Create right side address block
    address_style = ParagraphStyle(
        'Address',
        parent=styles['Normal'],
        fontSize=9,
        alignment=TA_RIGHT,
        leading=12
    )
    header_right = Paragraph(
        "2219 S. Stoughton Rd. Madison WI 53716 | 800-227-8575<br/>"
        "18525 W. Bluemound Rd. Brookfield WI 53045 | 262-395-7100",
        address_style
    )
    
    header_data.append([header_left, header_right])
    header_table = Table(header_data, colWidths=['60%', '40%'])
    header_table.setStyle(TableStyle([
        ('ALIGN', (0, 0), (0, 0), 'LEFT'),
        ('ALIGN', (1, 0), (1, 0), 'RIGHT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))
    story.append(header_table)
    story.append(Spacer(1, 20))
    
    # Add the gray Project Information header
    project_header_style = ParagraphStyle(
        'ProjectHeader',
        parent=styles['Normal'],
        fontSize=12,
        alignment=TA_LEFT,
        textColor=colors.white,
        backColor=colors.gray,
        fontName='Helvetica-Bold',
        leading=16,
        spaceBefore=10,
        spaceAfter=10,
        leftIndent=6
    )
    story.append(Paragraph("Project Information", project_header_style))
    story.append(Spacer(1, 20))
    
    # Process the rest of the content
    for line in lines:
        line = line.strip()
        if not line:
            continue
            
        # Skip the first table row which contains our header
        if line.startswith('| ![Allen Kitchen & Bath Logo]'):
            continue
            
        elif line.startswith('# '):
            # Main title
            title = line[2:]
            story.append(Paragraph(title, title_style))
            story.append(Spacer(1, 20))
            
        elif line.startswith('## '):
            # Section heading
            heading = line[3:]
            story.append(Paragraph(heading, heading_style))
            story.append(Spacer(1, 15))
            
        elif line.startswith('|') and not '---' in line:
            # Table row
            in_table = True
            cells = [cell.strip() for cell in line.split('|')[1:-1]]
            formatted_cells = []
            
            for cell in cells:
                if cell.startswith('**') and cell.endswith('**'):
                    # Bold text
                    cell = cell[2:-2]
                    formatted_cells.append(Paragraph(f'<b>{cell}</b>', bold_style))
                else:
                    formatted_cells.append(Paragraph(cell, normal_style))
            
            if formatted_cells:
                table_data.append(formatted_cells)
                
        elif line == '---':
            # Horizontal rule
            story.append(Spacer(1, 20))
            
        elif line.startswith('**') and line.endswith('**'):
            # Bold text
            text = line[2:-2]
            story.append(Paragraph(f'<b>{text}</b>', bold_style))
            story.append(Spacer(1, 10))
            
        elif line.startswith('*') and line.endswith('*'):
            # Italic text
            text = line[1:-1]
            story.append(Paragraph(f'<i>{text}</i>', normal_style))
            story.append(Spacer(1, 10))
            
        else:
            # Regular text or end of table
            if in_table and not line.startswith('|'):
                # End of table, add it to story
                if table_data:
                    t = Table(table_data, hAlign='LEFT')
                    t.setStyle(TableStyle([
                        ('BACKGROUND', (0, 0), (-1, 0), colors.lightgrey),
                        ('TEXTCOLOR', (0, 0), (-1, 0), colors.black),
                        ('ALIGN', (2, 0), (-1, -1), 'RIGHT'),
                        ('ALIGN', (0, 0), (1, -1), 'LEFT'),
                        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                        ('FONTSIZE', (0, 0), (-1, -1), 9),
                        ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
                        ('BACKGROUND', (0, 1), (-1, -1), colors.white),
                        ('GRID', (0, 0), (-1, -1), 0.5, colors.black),
                        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                    ]))
                    story.append(t)
                    story.append(Spacer(1, 12))
                table_data = []
                in_table = False
            
            # Add regular text
            if line:
                story.append(Paragraph(line, normal_style))
                story.append(Spacer(1, 5))
    
    # Handle table if still open at the end
    if in_table and table_data:
        t = Table(table_data, hAlign='LEFT')
        t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.lightgrey),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.black),
            ('ALIGN', (2, 0), (-1, -1), 'RIGHT'),
            ('ALIGN', (0, 0), (1, -1), 'LEFT'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
            ('BACKGROUND', (0, 1), (-1, -1), colors.white),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.black),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ]))
        story.append(t)
        story.append(Spacer(1, 12))
    
    doc.build(story)
    pdf_buffer.seek(0)
    return pdf_buffer 