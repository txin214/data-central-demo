def group_quote_line_items(quote):
    """
    Group quote line items by category and calculate subtotals.
    This utility function extracts the common logic used in:
    - product_quote_report
    - preview_quote_report  
    - generate_pdf_report
    
    Args:
        quote: ProductQuote instance (should have prefetched line_items__product__category)
        
    Returns:
        list: List of tuples (category, items, subtotal)
    """
    category_groups = defaultdict(list)
    category_subtotals = defaultdict(Decimal)

    # Use prefetched line_items if available, otherwise fall back to all()
    # Check if prefetch_related was used by checking if _prefetched_objects_cache exists
    if hasattr(quote, '_prefetched_objects_cache') and 'line_items' in quote._prefetched_objects_cache:
        line_items = quote._prefetched_objects_cache['line_items']
    else:
        # Fallback: prefetch if not already prefetched
        line_items = quote.line_items.select_related('product__category').all()
    
    for line_item in line_items:
        category = line_item.product.category.product_category if line_item.product.category else "Uncategorized"
        category_groups[category].append(line_item)
        unit_price = Decimal(line_item.unit_price) if line_item.unit_price else Decimal(0)
        line_item.total = unit_price * Decimal(line_item.quantity)
        category_subtotals[category] += line_item.total

    # Combine groups and subtotals into a list of tuples
    grouped_data = [
        (category, items, category_subtotals[category])
        for category, items in category_groups.items()
    ]
    
    return grouped_data


def generate_quote_markdown(quote, grouped_data):
    """
    Generate markdown content from quote report data.
    """
    markdown_content = f"""<div style="margin-bottom: 0;">
        <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 10px;">
            <div style="flex: 0 0 180px;">
                <img src="/static/crm/nologo.png" alt="Allen Kitchen & Bath Logo" style="width: 180px; height: auto;">
            </div>
            <div style="text-align: right; font-size: 11px; line-height: 1.4; color: #000;">
                <div style="margin-bottom: 2px;">800-227-8575</div>
                <div>2219 S. Stoughton Rd. Madison WI 53716 <span style="margin: 0 5px;">|</span> 608-274-9933</div>
                <div>18525 W. Bluemound Rd. Brookfield WI 53045 <span style="margin: 0 5px;">|</span> 262-395-7100</div>
            </div>
        </div>
        <div style="background-color: #808080; color: white; padding: 4px 8px; margin: 0;">
            <div style="font-weight: bold; font-size: 14px; text-align: center;">Project Information</div>
        </div>
    </div>

## Quote Details - {quote.customer.first_name} {quote.customer.last_name}

### Quote Information

**Customer:** {quote.customer.first_name} {quote.customer.last_name}  
**Quote Date:** {quote.quoted_date.strftime('%Y-%m-%d')}  
**Status:** {quote.status}  
**Quote ID:** {quote.id}

---

## Product Details

"""
    
    # Add product details in markdown table format
    markdown_content += "| Category | Product Description | Quantity | Unit Price ($) | Total Price ($) |\n"
    markdown_content += "|----------|-------------------|----------|----------------|-----------------|\n"
    
    for category, items, subtotal in grouped_data:
        # Add category header row
        markdown_content += f"| **{category}** | | | | |\n"
        
        # Add product rows
        for item in items:
            unit_price = item.unit_price if item.unit_price else Decimal('0')
            total = unit_price * Decimal(item.quantity)
            markdown_content += f"| | {item.product_description} | {item.quantity} | {unit_price:.2f} | {total:.2f} |\n"
        
        # Add subtotal row
        markdown_content += f"| **Subtotal for {category}** | | | | **${subtotal:.2f}** |\n"
        markdown_content += "| | | | | |\n"  # Empty row for spacing
    
    # Add final total
    markdown_content += f"\n**Quote Subtotal:** ${quote.subtotal:.2f}\n"
    
    # Add footer
    markdown_content += f"""
---

*Generated by Allen Kitchen & Bath on {quote.quoted_date.strftime('%Y-%m-%d %H:%M')}*
"""
    
    return markdown_content


